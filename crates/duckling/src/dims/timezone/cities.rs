//! Closed allowlist of cities → IANA zones. Ambiguous names have one row per zone.

#[derive(Clone, Copy, Debug)]
pub struct City {
    pub aliases: &'static [&'static str],
    pub iana: &'static str,
    pub label: &'static str,
    pub qualifiers: &'static [&'static str],
    pub rank: u8,
    pub fallback_offset_min: i32,
}

const fn c(
    aliases: &'static [&'static str],
    iana: &'static str,
    label: &'static str,
    qualifiers: &'static [&'static str],
    rank: u8,
    fallback_offset_min: i32,
) -> City {
    City { aliases, iana, label, qualifiers, rank, fallback_offset_min }
}

