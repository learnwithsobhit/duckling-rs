#!/usr/bin/env python3
"""Generate Rust data tables from upstream Time/Computed.hs and Time/TimeZone/Parse.hs."""
import re, os
root = os.path.join(os.path.dirname(__file__), "..")
up = os.path.join(root, "vendor/duckling/Duckling/Time")
out = os.path.join(root, "crates/duckling/src/dims/time")

def snake(n):
    return re.sub(r'([A-Z])', lambda m: '_' + m.group(1).lower(), n).lstrip('_')

src = open(os.path.join(up, "Computed.hs"), encoding="utf8").read()
lines = ["// @generated by tools/gen_time_data.py from upstream Duckling.Time.Computed -- do not edit.",
         "// Each table lists (year, month, day); entries that are not valid dates were dropped upstream by `fromGregorianValid`.", ""]
names = []
for m in re.finditer(r"^(\w+)' = mapMaybe toTimeObjectM\n((?:\s+[\[,]\s+\(.*\n)+)\s+\]", src, re.M):
    name, body = m.group(1), m.group(2)
    tuples = re.findall(r"\((\d+), (\d+), (\d+)\)", body)
    names.append(name)
    lines.append(f"pub static {snake(name).upper()}: &[(i64, u32, u32)] = &[")
    for y, mo, d in tuples:
        lines.append(f"    ({y}, {mo}, {d}),")
    lines.append("];")
    lines.append("")
exports = re.search(r"module Duckling.Time.Computed\n  \((.*?)\) where", src, re.S).group(1)
exported = [x.strip() for x in exports.replace("\n", "").split(",")]
assert sorted(exported) == sorted(names), (set(exported) ^ set(names))
open(os.path.join(out, "computed_data.rs"), "w").write("\n".join(lines))
print(len(names), "computed tables")

tz = open(os.path.join(up, "TimeZone/Parse.hs"), encoding="utf8").read()
ents = re.findall(r'\( "(\w+)", TimeZone \(?(-?\d+)\)? (True|False) "(\w+)" \)', tz)
lines = ["// @generated by tools/gen_time_data.py from upstream Duckling.Time.TimeZone.Parse -- do not edit.",
         "pub static TIMEZONES: &[(&str, i32, bool)] = &["]
for n, off, summer, n2 in ents:
    assert n == n2
    lines.append(f'    ("{n}", {off}, {summer.lower()}),')
lines.append("];")
open(os.path.join(out, "tz_data.rs"), "w").write("\n".join(lines) + "\n")
print(len(ents), "time zones")
