#!/usr/bin/env python3
"""Generate crates/duckling/src/lang_dims.rs from upstream Duckling/Dimensions/<LANG>.hs."""
import re, glob, os
root = os.path.join(os.path.dirname(__file__), '..', 'vendor/duckling/Duckling/Dimensions')
out = ["// @generated by tools/gen_lang_dims.py; do not edit.",
       "use crate::locale::Lang;", "use crate::types::Dim;", "",
       "/// `Duckling.Dimensions.<LANG>.allDimensions`, in upstream order.",
       "pub fn lang_dimensions(lang: Lang) -> Vec<Dim> {", "    match lang {"]
for f in sorted(glob.glob(root + '/*.hs')):
    l = os.path.basename(f)[:-3]
    if l in ('Common', 'Types'):
        continue
    src = open(f).read()
    body = src[re.search(r'allDimensions\s*=\s*\n', src).start():]
    dims = re.findall(r'Seal (\w+)', body)
    out.append(f"        Lang::{l} => vec![{', '.join('Dim::' + d for d in dims)}],")
out += ["    }", "}", ""]
open(os.path.join(os.path.dirname(__file__), '..', 'crates/duckling/src/lang_dims.rs'), 'w').write('\n'.join(out))
