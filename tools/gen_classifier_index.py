#!/usr/bin/env python3
"""Regenerate crates/duckling/src/classifier_index.rs from data/classifiers/*.json."""
import os
base = os.path.join(os.path.dirname(__file__), "..", "crates", "duckling")
names = sorted(f[:-5] for f in os.listdir(os.path.join(base, "data", "classifiers")) if f.endswith(".json"))
out = ["// @generated by tools/gen_classifier_index.py -- do not edit.",
       "pub fn lookup(name: &str) -> Option<&'static str> {", "    match name {"]
for n in names:
    out.append(f'        "{n}" => Some(include_str!("../data/classifiers/{n}.json")),')
out += ["        _ => None,", "    }", "}", ""]
open(os.path.join(base, "src", "classifier_index.rs"), "w").write("\n".join(out))
print(len(names), "classifiers")
